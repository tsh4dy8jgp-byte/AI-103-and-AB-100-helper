/**
 * MAINTAINED BY HAND. The generator that first produced this file lived outside the
 * repo and is gone, so edit the questions here directly.
 *
 * AB-100 question bank: Agentic AI Business Solutions Architect.
 *
 * Structure mirrors the AI-103 banks. Every item cites a verbatim bullet from the
 * published AB-100 skills-measured outline (see AB100_SYLLABUS) plus a Microsoft
 * Learn page. Questions are architecture and judgment scenarios rather than
 * implementation detail, matching the exam's solution-architect audience.
 */
const q = (
  id: string,
  domain: DomainId,
  topic: string,
  difficulty: Difficulty,
  prompt: string,
  options: string[],
  explanation: string,
  syllabus: SyllabusRef,
  caseStudyId?: string,
): Question => {
  // The correct answer is authored first, then rotated to a deterministic position
  // so the answer key stays balanced across the bank.
  const shift = [...id].reduce((sum, character) => sum + character.charCodeAt(0), 0) % options.length;
  return {
    id,
    exam: "ab100",
    domain,
    topic,
    difficulty,
    prompt,
    options: options.map((_, index) => options[(index + shift) % options.length]),
    correct: [(0 - shift + options.length) % options.length],
    explanation,
    syllabus,
    ...(caseStudyId ? { caseStudyId } : {}),
  };
};

